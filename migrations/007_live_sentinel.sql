-- 007: اصلاح نشانگر «آخرین تکه ارسال‌شده» در دستیار جلسه زنده
--
-- باگ: شماره تکه از صفر شروع می‌شود، اما مقدار پیش‌فرض last_sent_seq هم صفر بود.
-- شرط «تکه‌های بعد از آخرین ارسال» با > کار می‌کرد، پس تکه صفر همیشه حذف می‌شد
-- و اولین تکه هر جلسه هرگز به ایجنت نمی‌رسید.
--
-- راه‌حل: نشانگر «هیچ‌چیز ارسال نشده» از صفر به منفی یک منتقل می‌شود.
-- حالا شرط > -1 تکه صفر را هم شامل می‌شود.

alter table live.sessions alter column last_sent_seq set default -1;

-- نشست‌هایی که هنوز هیچ بازه‌ای نفرستاده‌اند، نشانگرشان به منفی یک می‌رود.
update live.sessions s
   set last_sent_seq = -1
 where s.last_sent_seq = 0
   and not exists (select 1 from live.segments g where g.session_id = s.id);
